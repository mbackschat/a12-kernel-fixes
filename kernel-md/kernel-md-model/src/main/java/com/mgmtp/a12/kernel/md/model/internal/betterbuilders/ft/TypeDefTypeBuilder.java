package com.mgmtp.a12.kernel.md.model.internal.betterbuilders.ft;

import com.mgmtp.a12.kernel.md.model.a12internal.fieldtypes.FieldType;
import com.mgmtp.a12.kernel.md.model.a12internal.fieldtypes.TypeDefType;

public class TypeDefTypeBuilder extends FieldTypeBuilder<TypeDefTypeBuilder, TypeDefType.TypeDefTypeBuilder> {
	private TypeDefTypeBuilder() {
		super(TypeDefType.builder());
	}

	public static TypeDefTypeBuilder builder() {
		return new TypeDefTypeBuilder();
	}

	/**
	 * @return return a TypeDefTypeBuilder that has some arbitrary values set for mandatory parameters,
	 * 		in order to make it easier to use in tests that don't care about the value of those parameters
	 * 		<p>
	 * 		<em>Note</em> This method was introduced mostly to let existing tests continue to work without
	 * 		significant changes. It should never be used for production code.
	 */
	public static TypeDefTypeBuilder builderWithDefaultsForTests() {
		return TypeDefTypeBuilder.builder()
				.modify(wb -> wb.id("typedef"));
	}

	@Override protected TypeDefTypeBuilder self() {
		return this;
	}

	@Override
	public FieldType build() {
		return wrappedAutogeneratedBuilder.build();
	}
}
