package com.mgmtp.a12.kernel.md.model.migration.internal;

/**
 * Result type of migration.
 *
 * <ul>
 * <li><code>SUCCESSFUL</code> means that there are no errors occurred during migration.</li>
 * <li><code>FAILED</code> means that at least one error occurs during migration. Please consider
 * {@link MigrationResult#getErrors()} to see more details.</li>
 * <li><code>NOT_REQUIRED</code> means that the current model is up-to-date and does not need to be migrated</li>
 * </ul>
 */
public enum MigrationResultType {
	SUCCESSFUL,
	FAILED,
	NOT_REQUIRED
}
