package com.mgmtp.a12.kernel.md.model.migration.internal.json;

import com.fasterxml.jackson.databind.JsonNode;
import com.mgmtp.a12.kernel.md.model.migration.internal.MigrationError;
import com.mgmtp.a12.kernel.md.model.migration.internal.MigrationErrorType;
import com.mgmtp.a12.kernel.md.model.migration.internal.exception.MigrationException;
import com.mgmtp.a12.kernel.md.model.migration.internal.utils.ModelJsonUtil;
import com.mgmtp.a12.kernel.md.model.migration.internal.validation.ModelValidator;

/**
 * Implementation of {@link ModelValidator} for document models in json format.
 */
public class DocumentModelJsonValidator implements ModelValidator<JsonNode> {

	@Override
	public void validate(JsonNode model) {
		if (!ModelJsonUtil.isValidDocumentModel(model)) {
			throw new MigrationException(
					new MigrationError(MigrationErrorType.MODEL_CONTENT_NOT_SUPPORTED)
							.withMessage("The model does not seem to be a valid document model."));
		}
	}

}
