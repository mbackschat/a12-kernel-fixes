package com.mgmtp.a12.kernel.core.codegen.internal.generator.backingbeans.utils;

import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.function.Consumer;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.stringtemplate.v4.ST;
import org.stringtemplate.v4.STGroup;
import org.stringtemplate.v4.STGroupFile;

import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.serviceparams.CodeProfileType;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.serviceparams.ICodeGeneratorParameters.Product;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.serviceparams.ICodeGeneratorParameters.ProgrammingLanguage;

/**
 * Klasse dient zum zentralen Ansteuern der StringTemplates. Default-Werte sind
 * {@link ProgrammingLanguage#JAVA}, {@link Product#VALIDATION} und {@link CodeProfileType#CP_STANDARD}.
 * <p>
 * Text als Zielsprache wird wegen der leichteren Lesbarkeit des Codes über andere MethodenNamen
 * angesteuert da es sich ja auch nicht um eine Zielsprache im engeren Sinne handelt.
 */
public class StringTemplateUtil {

	private static final ThreadLocal<StringTemplateUtil> INSTANCE_HOLDER = new ThreadLocal<>();

	private static final Logger LOGGER = LoggerFactory.getLogger(StringTemplateUtil.class);
	private static final String STRING_TEMPLATES_ENCODING = "UTF-8";

	private final Map<String, STGroup> stGroupCache = new ConcurrentHashMap<>();

	public static final String TEMPLATE_FILE_SEPARATOR = "/";

	private static final String TEMPLATE_PARAM_NAME = "t";

	private StringTemplateUtil() {
	}

	/**
	 * Liefert eine ThreadLocal-Instanz der Klasse.
	 *
	 * @return
	 */
	public static StringTemplateUtil getInstance() {
		StringTemplateUtil myInstance = INSTANCE_HOLDER.get();
		if (myInstance == null) {
			myInstance = new StringTemplateUtil();
			INSTANCE_HOLDER.set(myInstance);
		}

		return INSTANCE_HOLDER.get();
	}

	static void removeThreadLocalInstance() {
		StringTemplateUtil myInstance = INSTANCE_HOLDER.get();
		if (myInstance != null) {
			INSTANCE_HOLDER.remove();
		}
	}

	ST getTemplate(String templatePath, Consumer<STGroup> groupAdapter) {
		try {
			int idx = templatePath.lastIndexOf(TEMPLATE_FILE_SEPARATOR);
			String templateDir = "";
			String templateName = templatePath;
			if (idx > -1) {
				templateDir = "internal/" + templatePath.substring(0, idx);
				templateName = templatePath.substring(idx + 1);
			}

			STGroup tempateGroup = getActCodeGroup(templateDir);
			tempateGroup.setListener(new ThrowingErrorListener());
			tempateGroup.registerModelAdaptor(Object.class, new BetterObjectModelAdaptor<>());
			groupAdapter.accept(tempateGroup);
			return tempateGroup.getInstanceOf(templateName);
		} catch (Exception e) {
			String msg = "Error while instantiating template \"" + templatePath + "\".";
			throw new IllegalArgumentException(msg, e);
		}
	}

	/**
	 * Create the template code for the given.
	 *
	 * @param parameterClass
	 * 		the class containing the parameters used by the template.
	 * @param templateName
	 * 		the name of the template.
	 * @param groupAdapter
	 * 		a consumer that can be used to set additional parameters for the {@link STGroup}. E.g. additional model adapters.
	 * @return the code generated by the template.
	 */
	public String getTemplateCode(ICodeOutput parameterClass, String templateName, Consumer<STGroup> groupAdapter) {
		ST template = getTemplate(templateName, groupAdapter);
		if (template == null) {
			String errorMsg = "Template <" + templateName + "> not found";
			LOGGER.error(errorMsg);
			throw new IllegalArgumentException(errorMsg);
		}

		template.add(TEMPLATE_PARAM_NAME, parameterClass);
		return template.render();
	}

	private STGroup getActCodeGroup(String templateGroup) {
		return (stGroupCache.computeIfAbsent(templateGroup, tg ->
				new STGroupFile(templateGroup + ".stg", STRING_TEMPLATES_ENCODING, '<', '>')));
	}
}
