package com.mgmtp.a12.kernel.core.service.internal.extservices;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Collectors;

import com.mgmtp.a12.kernel.core.parser.internal.check.util.EntityUtils;
import com.mgmtp.a12.kernel.core.parser.internal.grammar.languages.ConditionMultiLanguageHandler;
import com.mgmtp.a12.kernel.core.parser.internal.parsebaum.util.FeldIdUtil;
import com.mgmtp.a12.kernel.core.service.internal.serviceparams.LanguageSpecificPropertiesLookup;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IEC;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IEntity;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IField;

/**
 * Implementation of a rule representing a solitary field test.
 * <p>
 * Rules of this type are created by {@link AutogeneratedRulesService}.
 */
class SolitaryFieldRuleImpl implements IAutogeneratedRule {

	private static final String FIELD_POSITIVE_CONDITION_KEY = "fieldFilledTemplate";
	private static final String FIELD_NEGATIVE_CONDITION_KEY = "noFieldFilledTemplate";
	private static final String GROUP_NEGATIVE_CONDITION_KEY = "noGroupFilledTemplate";
	private static final String AND_KEY = "and";

	static final String RULE_ERROR_CODE = "solitaryIndex";
	private static final String RULE_NAME_SUFFIX = "_solo";

	private final IField field;
	private final String ruleName;
	private final String errorConditionText;
	private final ConditionMultiLanguageHandler mlh;

	public SolitaryFieldRuleImpl(IField field, IEC ec, Locale languageUsedInConditionText, ConditionMultiLanguageHandler mlh) {
		this.field = field;
		this.mlh = mlh;

		String parentPath = EntityUtils.getParentPath(field.getFullName());
		String errorEntityShortName = EntityUtils.getShortName(field.getFullName());
		String ruleShortName = RULE_NAME_PREFIX + errorEntityShortName + RULE_NAME_SUFFIX;
		this.ruleName = EntityUtils.createPath(parentPath, ruleShortName);

		this.errorConditionText = createErrorConditionText(field, ec, languageUsedInConditionText);
	}

	private String createErrorConditionText(IField field, IEC ec, Locale locale) {
		List<String> ruleParts = new ArrayList<>();
		LanguageSpecificPropertiesLookup lookup = new LanguageSpecificPropertiesLookup(locale);
		String fieldPositiveConditionTemplate = lookup.getProperty(FIELD_POSITIVE_CONDITION_KEY);
		String fieldShortName = EntityUtils.getShortName(field.getFullName());
		ruleParts.add(String.format(fieldPositiveConditionTemplate, FeldIdUtil.quoteNameIfNecessary(fieldShortName, mlh)));

		String parentPath = EntityUtils.getParentPath(field.getFullName());
		List<IEntity> entities = ec.getDirectlyContainedEntities(parentPath);
		Map<Boolean, List<IEntity>> fieldsAndGroups = entities.stream()
				.filter(e -> !e.getFullName().equals(field.getFullName()))
				.collect(Collectors.groupingBy(IEntity::isField));

		List<IEntity> fields = fieldsAndGroups.get(true);
		if (fields != null && !fields.isEmpty()) {
			String fieldNegativeConditionTemplate = lookup.getProperty(FIELD_NEGATIVE_CONDITION_KEY);
			String fieldNames = fields.stream()
					.map(e -> FeldIdUtil.quoteNameIfNecessary(EntityUtils.getShortName(e.getFullName()), mlh))
					.collect(Collectors.joining(", "));
			ruleParts.add(String.format(fieldNegativeConditionTemplate, fieldNames));
		}

		List<IEntity> groups = fieldsAndGroups.getOrDefault(false, new ArrayList<>()).stream()
				.filter(g -> !ec.getAllContainedFields(g.getFullName()).isEmpty())
				.collect(Collectors.toList());
		if (!groups.isEmpty()) {
			String groupNegativeConditionTemplate = lookup.getProperty(GROUP_NEGATIVE_CONDITION_KEY);
			String groupNames = groups.stream()
					.map(e -> FeldIdUtil.quoteNameIfNecessary(EntityUtils.getShortName(e.getFullName()), mlh)
							+ (EntityUtils.isRepeatableOnLowestLevel(e) ? "*" : "")).collect(Collectors.joining(", "));
			ruleParts.add(String.format(groupNegativeConditionTemplate, groupNames));
		}

		String andStr = lookup.getProperty(AND_KEY);
		return ruleParts.stream()
				.collect(Collectors.joining(" " + andStr + " "));
	}

	@Override
	public String getErrorConditionText() {
		return errorConditionText;
	}

	@Override
	public IEntity getErrorEntity() {
		return field;
	}

	@Override
	public String getFullName() {
		return ruleName;
	}

	@Override
	public String getErrorCode() {
		return RULE_ERROR_CODE;
	}

	@Override
	public GenerationType getGenerationType() {
		return GenerationType.SOLITARY_FIELD;
	}

	@Override
	public RuleSeverityType getSeverityType() {
		return RuleSeverityType.ERROR;
	}

	@Override public List<String> getCustomRefErrorEntitiesIfFilled() {
		return List.of(); // the SolitaryField Rules are not manually modeled and don't have customRefErrorEntities
	}

	@Override public List<String> getCustomRefErrorEntitiesIfNotFilled() {
		return List.of(); // the SolitaryField Rules are not manually modeled and don't have customRefErrorEntities
	}
}
