package com.mgmtp.a12.kernel.core.service.internal.extservices;

import java.util.List;
import java.util.Locale;
import java.util.Objects;
import java.util.stream.Collectors;

import com.mgmtp.a12.kernel.core.extmpspecifics.internal.utils.ExtmpUtils;
import com.mgmtp.a12.kernel.core.parser.internal.check.util.EntityUtils;
import com.mgmtp.a12.kernel.core.parser.internal.check.util.FieldUtils;
import com.mgmtp.a12.kernel.core.parser.internal.grammar.languages.ConditionMultiLanguageHandler;
import com.mgmtp.a12.kernel.core.service.internal.extservices.IAutogeneratedRule.GenerationType;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IEC;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IField;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IGroup;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.serviceparams.ICodeGeneratorParameters.ProgrammingLanguage;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.serviceparams.IModelSpecificSettings;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.config.IProjectSpecificSettings;

/**
 * An instance of <code>AutogeneratedRulesService</code> creates rule for additional information
 * specified in the {@link IEC}-hierarchy.
 * E.g. rules can be generated for mandatory fields specified by the property
 * {@link IField#isMandatory()}:
 * <code>new AutogeneratedRulesService(ec, false).createRulesForMandatoryField();</code>.
 */
public class AutogeneratedRulesService {
	private final boolean isHModel;
	private final IEC ec;
	private final Locale languageUsedInConditionText;
	private final boolean hasAssignedModel;
	private final ProgrammingLanguage programmingLanguage;
	private final ConditionMultiLanguageHandler mlh;

	public AutogeneratedRulesService(IEC ec, IModelSpecificSettings modelSpecificSettings, IProjectSpecificSettings pss,
			ProgrammingLanguage programmingLanguage) {
		this.ec = ec;
		this.isHModel = ExtmpUtils.isHModel(modelSpecificSettings);
		this.languageUsedInConditionText = modelSpecificSettings.getLanguageUsedInConditionText();
		this.mlh = new ConditionMultiLanguageHandler(languageUsedInConditionText, pss);
		this.hasAssignedModel = ExtmpUtils.hasAssignedUXMLModel(modelSpecificSettings);
		this.programmingLanguage = programmingLanguage;
	}

	/**
	 * Create all rules for the mandatory fields specified in the {@link IEC} by the property
	 * {@link IField#isMandatory()}.
	 * <p>
	 * The rule condition text will depend on the requiredness semantic of the field:
	 * <ul>
	 *     <li>{@link IField.IRequirednessConfig.Mode#absoluteOrRelativeToNextRepAncestor}
	 *     <ul>
	 *         <li>if the field is not repeatable: <code>FieldNotFilled(&lt;fieldName&gt;)</code></li>
	 *         <li>if the field is repeatable: <code>GroupFilled(&lt;repeatableAncestorPath&gt;) And FieldNotFilled(&lt;fieldName&gt;)</code></li>
	 *     </ul>
	 *     </li>
	 *     <li>{@link IField.IRequirednessConfig.Mode#relativeToParent}: <code>GroupFilled(&lt;parentPath&gt;) And FieldNotFilled(&lt;fieldName&gt;)</code></li>
	 * </ul>
	 *
	 * <p>
	 * In the special case of old world ExtMP root group fields the condition will contain
	 * <code>VordruckAngegeben</code> instead of <code>GroupFilled</code>.
	 * <p>
	 * In the special case of old world ExtMP repeatable fields the condition will be extended
	 * with <code>.#Zeile</code> direct after <code>RuleGroup</code>.
	 *
	 * @return the list of rules for mandatory fields.
	 */
	public List<IAutogeneratedRule> createRulesForMandatoryFields() {
		return EntityUtils.getAllFields(ec).stream()
				.filter(IField::isMandatory)
				.map(f -> createMandatoryRuleForField(f, determineRelativeTo(f)))
				.collect(Collectors.toList());
	}

	/**
	 * Create constraints for correct index fields specified in the {@link IEC} by the property
	 * {@link IGroup#getIndexFieldNames()}:
	 * <ul>
	 * <li>Uniqueness: The rule condition text will be
	 * <code>RepetitionNotUnique(&lt;relativeFieldName&gt;)</code>. The rule group will be the
	 * ancestor of the context containing the field. In the special case of a root group field,
	 * the rule group will be the root group, too. The relative field name is built
	 * accordingly.</li>
	 * <li>Mandatory: see also
	 * {@link AutogeneratedRulesService#createMandatoryRuleForField(IField, String)}.</li>
	 * </ul>
	 *
	 * @param considerDefaultValue
	 * 		if <code>true</code> the result does not contain the corresponding mandatory rules
	 * 		for index fields for which a default value was defined.
	 * @return the list of auto-generated rules for index fields.
	 */
	public List<IAutogeneratedRule> createRulesForIndexFields(boolean considerDefaultValue) {
		List<IAutogeneratedRule> result = getAllIndexFields().stream()
				.filter(EntityUtils::isInRepeatableGroup)
				.map(f -> createUniquenessRuleForField(f, GenerationType.UNIQUE_FIELD))
				.collect(Collectors.toList());
		result.addAll(createMandatoryRulesForIndexFields(considerDefaultValue));
		if (hasAssignedModel && this.programmingLanguage != ProgrammingLanguage.VBA) {
			result.addAll(createNonSoloIndexFieldRules());
		}
		return result;
	}

	private List<IAutogeneratedRule> createNonSoloIndexFieldRules() {
		return getAllIndexFields().stream()
				.map(this::createNonSoloIndexFieldRule)
				.collect(Collectors.toList());
	}

	private IAutogeneratedRule createNonSoloIndexFieldRule(IField field) {
		return new SolitaryFieldRuleImpl(field, ec, languageUsedInConditionText, mlh);
	}

	/**
	 * @param considerDefaultValue
	 * 		if <code>true</code> the result does not contain the corresponding mandatory rules
	 * 		for index fields for which a default value was defined.
	 * @return the list of mandatory rules for index fields.
	 */
	public List<IAutogeneratedRule> createMandatoryRulesForIndexFields(boolean considerDefaultValue) {
		return getAllIndexFields().stream()
				// for mandatory fields the rule is created at AutogeneratedRulesService#createRulesForMandatoryFields()
				// enum fields with s value are not mandatory fields, if the default value should be considered
				// reason: the s value acts as a default value for the index field at runtime
				.filter(f -> !f.isMandatory() && !(considerDefaultValue && FieldUtils.isSValueDefined(f)))
				.map(f -> createMandatoryRuleForField(f, EntityUtils.getParentPath(f.getFullName())))
				.collect(Collectors.toList());
	}

	/**
	 * @return all index fields contained in the {@link IEC}.
	 */
	private List<IField> getAllIndexFields() {
		return EntityUtils.getAllGroups(ec).stream()
				.flatMap(g -> g.getIndexFieldNames().stream()
						// According to the validation, the field may also be referenced relatively.
						.map(f -> EntityUtils.getEntityInGroup(ec, f, g.getFullName())))
				// Erroneous index fields should be ignored
				.filter(Objects::nonNull)
				.map(e -> (IField) e)
				.collect(Collectors.toList());
	}

	/**
	 * Create a rule for the given field, specifying that the field value must be unique in the
	 * context of the parent group.
	 *
	 * @param field
	 * 		the index field..
	 * @return the corresponding rule.
	 */
	private IAutogeneratedRule createUniquenessRuleForField(IField field, GenerationType generationType) {
		return new UniqueFieldRuleImpl(field, generationType, languageUsedInConditionText, mlh);
	}

	/**
	 * Create a rule for the given field, specifying that the field is mandatory in the context of
	 * the parent group.
	 *
	 * @param field
	 * 		the field to be mandatory.
	 * @return the corresponding rule.
	 */
	private IAutogeneratedRule createMandatoryRuleForField(IField field, String relativeTo) {
		return new MandatoryFieldRuleImpl(field, relativeTo, isHModel, languageUsedInConditionText, mlh);
	}

	/**
	 * @return the group path which the requiredness of the field depends on, or {@code null} if the field is absolutely required.
	 */
	private String determineRelativeTo(IField field) {
		assert field.getRequirednessConfig().isPresent();
		return switch (field.getRequirednessConfig().get().getMode()) {
			case relativeToParent -> EntityUtils.getParentPath(field.getFullName());
			case absoluteOrRelativeToNextRepAncestor -> EntityUtils.getLowestRepeatableGroupPath(field);
		};
	}

}