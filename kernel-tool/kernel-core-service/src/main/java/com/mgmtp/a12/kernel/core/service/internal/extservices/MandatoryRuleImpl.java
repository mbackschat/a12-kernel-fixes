package com.mgmtp.a12.kernel.core.service.internal.extservices;

import java.util.List;
import java.util.Locale;

import com.mgmtp.a12.kernel.core.parser.internal.check.util.EntityUtils;
import com.mgmtp.a12.kernel.core.parser.internal.grammar.languages.ConditionMultiLanguageHandler;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IField;

public abstract class MandatoryRuleImpl implements IAutogeneratedRule {

	public static final String RULE_NAME_SUFFIX = "_req";

	protected final IField errorEntity;
	protected final String errorEntityName;
	protected final String relativeTo;
	protected final String rulePath;
	protected final String errorConditionText;
	protected final Locale locale;
	protected final ConditionMultiLanguageHandler mlh;

	public MandatoryRuleImpl(IField mandatoryField, String relativeTo, boolean isHModel, Locale languageUsedInConditionText,
			ConditionMultiLanguageHandler mlh) {
		this.errorEntity = mandatoryField;
		this.errorEntityName = EntityUtils.getShortName(errorEntity.getFullName());
		this.relativeTo = relativeTo;

		String parentPath = EntityUtils.getParentPath(mandatoryField.getFullName());
		String ruleName = RULE_NAME_PREFIX + errorEntityName + RULE_NAME_SUFFIX;

		this.rulePath = EntityUtils.createPath(parentPath, ruleName);
		this.locale = languageUsedInConditionText;
		this.mlh = mlh;

		this.errorConditionText = createErrorConditionText(parentPath, isHModel);
	}

	protected abstract String createErrorConditionText(String parentPath, boolean isHModel);

	@Override
	public String getFullName() {
		return rulePath;
	}

	@Override
	public String getErrorConditionText() {
		return errorConditionText;
	}

	@Override
	public IField getErrorEntity() {
		return errorEntity;
	}

	@Override
	public RuleSeverityType getSeverityType() {
		return RuleSeverityType.ERROR;
	}

	@Override public List<String> getCustomRefErrorEntitiesIfFilled() {
		return List.of(); // the Mandatory* Rules are not manually modeled and don't have customRefErrorEntities
	}

	@Override public List<String> getCustomRefErrorEntitiesIfNotFilled() {
		return List.of(); // the Mandatory* Rules are not manually modeled and don't have customRefErrorEntities
	}
}