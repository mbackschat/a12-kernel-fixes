package com.mgmtp.a12.kernel.core.codegen.internal.generator.backingbeans.conditions;

import com.mgmtp.a12.kernel.core.codegen.internal.generator.backingbeans.utils.STParameterClassBase;
import com.mgmtp.a12.kernel.core.codegen.internal.generator.backingbeans.utils.StringTemplateGroup;
import com.mgmtp.a12.kernel.core.parsetree.a12internal.api.condition.ICondition;

@StringTemplateGroup("conditions/")
public abstract class CodeGenCondition extends STParameterClassBase implements ICondition {

	/**
	 * Method is needed for code generation. ".isKnownAndTrue()" cannot simply be written into the
	 * templates since different methods are needed for Java, Cpp and VBA.
	 */
	public String getBooleanCode() {
		String code = toCode();
		if (code.charAt(code.length() - 1) == '\n') {
			char[] codeAsChar = code.toCharArray();
			codeAsChar[code.length() - 1] = ' ';
			code = new String(codeAsChar);
		}
		String postfix = new ConditionSuffix().toCode();
		return code + postfix;
	}
}
