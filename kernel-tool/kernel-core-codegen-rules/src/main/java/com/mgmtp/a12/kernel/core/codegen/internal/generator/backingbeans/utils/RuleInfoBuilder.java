/**
 * Creates a {@link RuleInfo} cache object from an IRule.
 */
public class RuleInfoBuilder {

	private final IRule rule;
	private ICondition condition;
	private ICondition conditionPartiallyExpanded;
	private ICondition conditionGroupExpanded;
	/**
	 * can be null if no customRefErrorEntities exist
	 */
	private ICondition conditionNoExpandForCustomRefErrorEntities;
	private Map<String, IErrortextParameter> errorTextParameters;
	private final int ruleNumber;
	private boolean errorInCondition = false;

	private final CodeGenData data;
	private final IProblemReporter pr;

	public RuleInfoBuilder(IRule r, CodeGenData data, IProblemReporter pr, int ruleNumber) {
		this.rule = r;
		this.ruleNumber = ruleNumber;

		this.data = data;
		this.pr = pr;
	}

	public ICondition getPartiallyExpandedCondition() {
		if (this.conditionPartiallyExpanded == null && !errorInCondition) {
			this.conditionPartiallyExpanded = parseCondition(ExpandMode.EXPAND_PARTIALLY);
		}
		return this.conditionPartiallyExpanded;
	}

	public ICondition getCondition() {
		if (this.condition == null && !errorInCondition) {
			this.condition = parseCondition(ExpandMode.EXPAND);
		}
		return this.condition;
	}

	public ICondition getConditionNoExpandForCustomRefErrorEntities() {
		if (!rule.hasCustomRefEntities()) {
			return null;
		}
		if (this.conditionNoExpandForCustomRefErrorEntities == null && !errorInCondition) {
			this.conditionNoExpandForCustomRefErrorEntities = parseCondition(ExpandMode.NO_EXPAND);
		}
		return this.conditionNoExpandForCustomRefErrorEntities;
	}

	private ICondition parseCondition(ExpandMode expandMode) {
		ParserService ps = new ParserService(data.getEc(), data.getModelSpecificSettings(), data.getPss(),
				IServiceConfiguration.ParserStrictness.STRICT);
		ICondition result = ps.parseAndCheckCondition(rule, rule.getErrorConditionText(), pr, expandMode);
		if (result == null) {
			errorInCondition = true;
		}
		return result;
	}

	public ICondition getGroupExpandedCondition() {
		ProgrammingLanguage programmingLanguage = data.getParams().getProgrammingLanguage();
		if (programmingLanguage != ProgrammingLanguage.JAVA &&
				programmingLanguage != ProgrammingLanguage.JAVA_SCRIPT_VK &&
				programmingLanguage != ProgrammingLanguage.CPLUS &&
				programmingLanguage != ProgrammingLanguage.GROOVY) {
			// For all languages besides Java, C++, JavaScript_VK and Groovy we do not want to include the group identifiers
			return getCondition();
		}

		if (this.conditionGroupExpanded == null && !errorInCondition) {
			this.conditionGroupExpanded = parseCondition(ExpandMode.EXPAND_AND_ADD_GROUPS);
		}
		return this.conditionGroupExpanded;
	}

	public IRule getRule() {
		return rule;
	}

	public boolean isUSBPattern() {
		return AnalyseService.referenziertIteration(getCondition(), IndexArt.USB);
	}

	public boolean isRootGroupPattern() {
		return AnalyseService.referenziertIteration(getCondition(), IndexArt.LFDNUMMER);
	}

	public boolean isUsbPatternForRootGroup() {
		return AnalyseService.isUSBPatternForRootGroups(getCondition());
	}

	public boolean isUseMultipleRootGroups() {
		return AnalyseService.referenziertMehrereVordrucke(getCondition());
	}

	public boolean isAlwaysEvaluated() {
		// (1) Negative conditions are evaluated always
		if (CanConditionFireEmptyVisitor.canConditionFireEmpty(getCondition(),
				EntityUtils.getRootGroupName(rule.getErrorEntity().getFullName()))) {
			return true;
		}
		// (2) error field is repeatable for rootgroup, but rule does not iterate
		if (rule.getErrorEntity().getMax()[0] > 1 && (!isRootGroupPattern())) {
			return true;
		}

		long maxUsb;
		if (rule.getErrorEntity() instanceof IExtmpEntity) {
			maxUsb = ((IExtmpEntity) rule.getErrorEntity()).getMaxUsb();
		} else {
			maxUsb = IExtmpEntity.UNDEFINED;
		}
		// (3) error field on usb group, but rule does not iterate over usb
		if (maxUsb > 0 && (!isUSBPattern())) {
			return true;
		}

		// (4) language feature AnzahlAngegebenerUSB is used
		if (AnalyseService.beinhaltetAnzahlAngegebenerUsb(getCondition())) {
			return true;
		}
		if (AnalyseService.beinhaltetAnzahlAngegebenerVordrucke(getCondition())) {
			return true;
		}

		if (AnalyseService.beinhaltetAnzahlAngegebenerFelderOrKontexteOrVerschiedenerWerteMitKleinerPruefung(getCondition())) {
			return true;
		}

		return false;

	}

	public int getSemanticIndexLevel() {
		return SemanticIndexLevelVisitor.getSemanticIndexLevel(getCondition(), rule.getErrorEntity().getFullName());
	}

	public Optional<Object> getUniqueSemanticIndex4ErrorField4NotIteratingLevel(int semanticIndexLevel) {
		return SemanticIndices4ErrorFieldVisitor.getUniqueSemanticIndex4NotIteratingLevel(getCondition(), rule.getErrorEntity(),
				semanticIndexLevel, data.getEc());
	}

	public int getRuleNumber() {
		return ruleNumber;
	}

	public Map<String, IErrortextParameter> getErrorTextParameters() {
		if (errorTextParameters == null) {
			this.errorTextParameters = new HashMap<>();
			if (!(rule instanceof IAutogeneratedRule) && !errorInCondition) {
				checkErrorTextsAndParseParameters();
			}
		}
		return errorTextParameters;
	}

	private void checkErrorTextsAndParseParameters() {
		RuleErrortextChecker checker = new RuleErrortextChecker(rule, getCondition(), data.getEc(),
				data.getModelSpecificSettings(), true);
		for (Locale l : data.getParams().getLanguages()) {
			errorTextParameters.putAll(
					checker.checkErrorMessageNotEmptyAndCorrect(rule.getErrorMessage(l), l, pr));
		}
	}

	public Map<Locale, String> getErrorMessages() {
		final Map<String, IErrortextParameter> parsedParameters = getErrorTextParameters();
		return rule.getErrorMessages().entrySet().stream()
				.collect(Collectors.toMap(Map.Entry::getKey,
						e -> replaceBaseYearParameter(e.getValue(), parsedParameters)));
	}

	/**
	 * Replaces a parameter of the form $BaseYear[+-n]$ ({@link IBaseYearParameter} in an error text.
	 * <p>
	 * Example: For the text {@code "Bla $BaseYear$ and $BaseYear-1$ and $BaseYear+10$"} in a model with base year 2013 the string
	 * {@code "Bla 2013 and 2012 and 2023"} is returned.
	 *
	 * @param text
	 * 		the {@link String} with parameters to be replaced.
	 * @param parsedParameters
	 * 		map containing the parsed {@link IBaseYearParameter}s, where the key is the non parsed parameter
	 * @return the given text with the base year parameters replaced.
	 */
	private String replaceBaseYearParameter(String text, Map<String, IErrortextParameter> parsedParameters) {
		if (text == null) {
			return null;
		}

		int baseYear = 0;
		if (data.getBaseYear() != null) {
			baseYear = Integer.parseInt(data.getBaseYear());
		}

		String[] parts = StringUtils.splitPreserveAllTokens(text, '$');
		for (int i = 1; i < parts.length; i = i + 2) {
			IErrortextParameter param = parsedParameters.get(parts[i]);
			if (param instanceof IBaseYearParameter) {
				String replacement;
				ICalculation calc = ((IBaseYearParameter) param).getCalculation();
				if (calc != null) {
					final int delta = Integer.parseInt(calc.format());
					replacement = Integer.toString(baseYear + delta);
				} else {
					replacement = Integer.toString(baseYear);
				}
				parts[i] = replacement;
			} else {
				// no replacement
				parts[i] = "$" + parts[i] + "$";
			}
		}

		return StringUtils.join(parts);
	}

	public RuleInfo build() {
		if (rule instanceof RuleInfo) {
			return (RuleInfo) rule;
		}

		if (rule instanceof IExtmpRule) {
			return new ExtmpRuleInfo(this);
		}

		return new RuleInfo(this);
	}
}
