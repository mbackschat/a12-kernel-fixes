package com.mgmtp.a12.kernel.core.codegen.internal.generator;

import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.Set;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.function.Predicate;
import java.util.stream.Collectors;

import com.mgmtp.a12.kernel.core.codegen.internal.generator.backingbeans.utils.RuleInfo;
import com.mgmtp.a12.kernel.core.codegen.internal.generator.backingbeans.utils.RuleInfoBuilder;
import com.mgmtp.a12.kernel.core.extmpspecifics.internal.utils.ExtmpUtils;
import com.mgmtp.a12.kernel.core.service.internal.extservices.AutogeneratedRulesService;
import com.mgmtp.a12.kernel.core.service.internal.extservices.IAutogeneratedRule;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IEC;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IRule;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.serviceparams.ICodeGeneratorParameters;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.serviceparams.IModelSpecificSettings;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.config.IProjectSpecificSettings;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.error.IProblemReporter;

/**
 * The complete set of model parameters for a code generation.
 */
public class CodeGenData extends CodeGenEntityData {
	private final List<? extends IRule> rules;
	private List<RuleInfo> ruleInfos;
	private List<RuleInfo> autoGenRuleInfos;
	private final boolean isReReDv;

	public CodeGenData(IEC ec, IModelSpecificSettings modelSpecificSettings, ICodeGeneratorParameters params,
			Collection<? extends IRule> rules,
			IProjectSpecificSettings pss) {
		super(ec, modelSpecificSettings, params, pss);
		// We sometimes want to adjust the rule set, so we need a copy
		this.rules = new ArrayList<>(rules);
		this.isReReDv = ExtmpUtils.isReReDv(modelSpecificSettings);
	}

	public CodeGenData(IEC ec, IModelSpecificSettings modelSpecificSettings, ICodeGeneratorParameters params,
			Collection<? extends IRule> rules,
			IProjectSpecificSettings pss, boolean isMappedFromReReDv) {
		super(ec, modelSpecificSettings, params, pss);
		// We sometimes want to adjust the rule set, so we need a copy
		this.rules = new ArrayList<>(rules);
		// at the moment, annotations cannot be defined for uXML models, so the second should not happen
		this.isReReDv = isMappedFromReReDv || ExtmpUtils.isReReDv(modelSpecificSettings);
	}

	public Collection<? extends IRule> getRules() {
		return rules;
	}

	/**
	 * Get the {@link RuleInfo}s for rules transmitted by the caller.
	 * <p>
	 * Auto-generated rules are not contained in this list.
	 *
	 * @param pr
	 * 		the problem reporter used for parsing the rules.
	 * @return the {@link RuleInfo}s for transmitted rules.
	 */
	public List<RuleInfo> getRuleInfos(IProblemReporter pr) {
		ensureRuleInfos(pr);
		return ruleInfos;
	}

	private void ensureRuleInfos(IProblemReporter pr) {
		if (ruleInfos == null) {
			this.ruleInfos = createRuleInfosForRules(rules, pr, 0);
		}
	}

	/**
	 * Get the {@link RuleInfo}s automatically generated rules.
	 * <p>
	 * The rules are generated by {@link AutogeneratedRulesService#createRulesForMandatoryFields()}.
	 *
	 * @param pr
	 * 		the problem reporter used for parsing the rules. For auto-generated rules, we
	 * 		never should get an error.
	 * @return the {@link RuleInfo}s for transmitted rules.
	 */
	public List<RuleInfo> getAutogenRuleInfos(IProblemReporter pr) {
		if (autoGenRuleInfos == null) {
			AutogeneratedRulesService ars = new AutogeneratedRulesService(ec, modelSpecificSettings, pss,
					params.getProgrammingLanguage());
			List<IAutogeneratedRule> additionalRules = ars.createRulesForMandatoryFields();
			additionalRules.addAll(ars.createRulesForIndexFields(false));
			this.autoGenRuleInfos = createRuleInfosForRules(additionalRules, pr, rules.size());
		}
		return autoGenRuleInfos;
	}

	private List<RuleInfo> createRuleInfosForRules(Collection<? extends IRule> rules, IProblemReporter pr, int startRuleNumber) {
		AtomicInteger ruleNumber = new AtomicInteger(startRuleNumber);
		return rules.stream()
				.map(r -> new RuleInfoBuilder(r, this, pr, ruleNumber.getAndIncrement()).build())
				.collect(Collectors.toList());
	}

	/**
	 * Filter out the rules specified by the given predicate.
	 *
	 * @param rulesToEliminate
	 * 		the predicate for the rules.
	 * @param problemReporter
	 * 		the problem reporter used when creating @link {@link RuleInfo}s. Parsing problems
	 * 		will be stored here.
	 */
	public void removeRules(Predicate<RuleInfo> rulesToEliminate, IProblemReporter problemReporter) {
		ensureRuleInfos(problemReporter);
		List<RuleInfo> ruleInfosToRemove = ruleInfos.stream()
				.filter(rulesToEliminate)
				.toList();

		ruleInfos.removeAll(ruleInfosToRemove);
		Set<IRule> rulesToRemove = ruleInfosToRemove.stream().map(RuleInfo::getRule).collect(Collectors.toSet());
		rules.removeAll(rulesToRemove);
		resortRuleInfos();
	}

	private void resortRuleInfos() {
		AtomicInteger ruleNumber = new AtomicInteger();
		ruleInfos.forEach(r -> r.setRuleNumber(ruleNumber.getAndIncrement()));
	}

	public boolean isReReDv() {
		return isReReDv;
	}
}
