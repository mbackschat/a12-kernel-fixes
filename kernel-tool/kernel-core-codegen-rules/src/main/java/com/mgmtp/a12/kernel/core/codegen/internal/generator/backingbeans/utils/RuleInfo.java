package com.mgmtp.a12.kernel.core.codegen.internal.generator.backingbeans.utils;

import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;

import com.mgmtp.a12.kernel.core.parsetree.a12internal.api.condition.ICondition;
import com.mgmtp.a12.kernel.core.service.internal.errortext.api.IErrortextParameter;
import com.mgmtp.a12.kernel.core.service.internal.extservices.IAutogeneratedRule;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IEntity;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IRule;

/**
 * Class for caching special attributes of an {@link IRule} object like the parsed condition.
 */
public class RuleInfo implements IRule {

	private final IRule rule;
	private final boolean isUSBPattern;
	private final boolean isRootGroupPattern;
	private final boolean isUsbPatternForRootGroup;
	private final ICondition condition;
	private final ICondition groupExpandedCondition;
	private final ICondition conditionNoExpandForCustomRefErrorEntities;
	private final Map<Locale, String> errorMessages;
	private final boolean isAlwaysEvaluated;
	private final boolean isUseMultipleRootGroups;
	private final int semanticIndexLevel;
	private int ruleNumber;
	private final ICondition conditionPartiallyExpanded;
	private final Optional<Object> uniqueSemanticIndex4ErrorField4NotIteratingLevel;
	/**
	 * Contains the parsed error text parameters. The key is the unparsed parameter (text between
	 * two dollars in the error text).
	 */
	private final Map<String, IErrortextParameter> errorTextParameters;

	public RuleInfo(RuleInfoBuilder builder) {
		this.rule = builder.getRule();
		this.condition = builder.getCondition();
		this.groupExpandedCondition = builder.getGroupExpandedCondition();
		this.conditionPartiallyExpanded = builder.getPartiallyExpandedCondition();
		this.conditionNoExpandForCustomRefErrorEntities = builder.getConditionNoExpandForCustomRefErrorEntities();
		this.ruleNumber = builder.getRuleNumber();
		if (condition != null) {
			this.isUSBPattern = builder.isUSBPattern();
			this.isRootGroupPattern = builder.isRootGroupPattern();
			this.isUsbPatternForRootGroup = builder.isUsbPatternForRootGroup();
			this.isAlwaysEvaluated = builder.isAlwaysEvaluated();
			this.isUseMultipleRootGroups = builder.isUseMultipleRootGroups();
			this.semanticIndexLevel = builder.getSemanticIndexLevel();
			this.uniqueSemanticIndex4ErrorField4NotIteratingLevel = builder.getUniqueSemanticIndex4ErrorField4NotIteratingLevel(
					semanticIndexLevel);
		} else {
			this.isUSBPattern = false;
			this.isRootGroupPattern = false;
			this.isUsbPatternForRootGroup = false;
			this.isAlwaysEvaluated = false;
			this.isUseMultipleRootGroups = false;
			this.semanticIndexLevel = -1;
			this.uniqueSemanticIndex4ErrorField4NotIteratingLevel = Optional.empty();
		}
		this.errorTextParameters = builder.getErrorTextParameters();
		this.errorMessages = builder.getErrorMessages();
	}

	public IRule getRule() {
		return rule;
	}

	public boolean isUSBPattern() {
		return isUSBPattern;
	}

	public boolean isRootGroupPattern() {
		return isRootGroupPattern;
	}

	public boolean isUsbPatternForRootGroup() {
		return isUsbPatternForRootGroup;
	}

	public ICondition getPartiallyExpandedCondition() {
		return conditionPartiallyExpanded;
	}

	public ICondition getConditionNoExpandForCustomRefErrorEntities() {
		return conditionNoExpandForCustomRefErrorEntities;
	}

	public ICondition getCondition() {
		return condition;
	}

	public boolean isAlwaysEvaluated() {
		return isAlwaysEvaluated;
	}

	public boolean isUseMultipleRootGroups() {
		return isUseMultipleRootGroups;
	}

	public int getRuleNumber() {
		return ruleNumber;
	}

	/**
	 * Sets the number of a rule. Usage of this method is necessary if rules are filtered out and
	 * the rules need to be reordered.
	 */
	public void setRuleNumber(int number) {
		this.ruleNumber = number;
	}

	@Override
	public String getFullName() {
		return rule.getFullName();
	}

	@Override
	public String getErrorConditionText() {
		return rule.getErrorConditionText();
	}

	@Override
	public String getErrorMessage(Locale loc) {
		return errorMessages.get(loc);
	}

	@Override
	public Map<Locale, String> getErrorMessages() {
		return errorMessages;
	}

	@Override
	public IEntity getErrorEntity() {
		return rule.getErrorEntity();
	}

	@Override
	public String getErrorCode() {
		return rule.getErrorCode();
	}

	@Override
	public RuleSeverityType getSeverityType() {
		return rule.getSeverityType();
	}

	@Override public boolean hasCustomRefEntities() {
		return rule.hasCustomRefEntities();
	}

	@Override public List<String> getCustomRefErrorEntitiesIfFilled() {
		return rule.getCustomRefErrorEntitiesIfFilled();
	}

	@Override public List<String> getCustomRefErrorEntitiesIfNotFilled() {
		return rule.getCustomRefErrorEntitiesIfNotFilled();
	}

	public ICondition getGroupExpandedCondition() {
		return groupExpandedCondition;
	}

	public IAutogeneratedRule.GenerationType getAutogenType() {
		if (rule instanceof IAutogeneratedRule) {
			return ((IAutogeneratedRule) rule).getGenerationType();
		} else {
			return null;
		}
	}

	public boolean isPreliminary() {
		// Currently the preliminary
		return getAutogenType() != null;
	}

	public int getSemanticIndexLevel() {
		return semanticIndexLevel;
	}

	public boolean hasUniqueSemanticIndex4ErrorField4NotIteratingLevel() {
		return uniqueSemanticIndex4ErrorField4NotIteratingLevel.isPresent();
	}

	public boolean isUniqueSemanticIndex4ErrorFieldConstant() {
		return uniqueSemanticIndex4ErrorField4NotIteratingLevel.isPresent() && uniqueSemanticIndex4ErrorField4NotIteratingLevel.get() instanceof String;
	}

	public Map<String, IErrortextParameter> getErrorTextParameters() {
		return errorTextParameters;
	}

}
