package com.mgmtp.a12.kernel.core.codegen.internal.generator.backingbeans.formatdefinition;

import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IFieldType;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IYesType;

/**
 * Definiert ein FeldJa Feld
 */
public class CodeGenYesTypeImpl extends CodeGenFeldTypBasis {

	private final String jaWert;

	public CodeGenYesTypeImpl(IFieldType type) {
		IYesType yesType = (IYesType) type;
		jaWert = yesType.getTrueValue();
	}

	public String getJaWert() {
		return jaWert;
	}

	public boolean equals(Object other) {
		if (this == other) {
			return true;
		}
		if (other == null) {
			return false;
		}
		if (other.getClass() != getClass()) {
			return false;
		}

		CodeGenYesTypeImpl o = (CodeGenYesTypeImpl) other;

		return (o.jaWert.equals(jaWert));
	}

	public int hashCode() {
		return jaWert.hashCode();
	}

	public String getClassnameSuffix() {
		return "Ja";
	}

}
