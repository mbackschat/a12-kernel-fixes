package com.mgmtp.a12.kernel.md.utils;

import static java.lang.annotation.ElementType.FIELD;
import static java.lang.annotation.RetentionPolicy.SOURCE;

import java.lang.annotation.Documented;
import java.lang.annotation.Retention;
import java.lang.annotation.Target;

/**
 * It is not necessary to adjust the value of serialVersionUID if this class is changed, because
 * object serialization is only used for server-internal caches. A12 Data-Services ensures that the
 * caches are invalidated in case of changes.
 */
@Documented
@Target({ FIELD })
@Retention(SOURCE)
public @interface NoNeedToAdaptSerialVersionUID {

}
